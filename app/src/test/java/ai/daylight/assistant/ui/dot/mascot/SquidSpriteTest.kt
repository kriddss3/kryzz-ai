package ai.daylight.assistant.ui.dot.mascot

import com.google.common.truth.Truth.assertThat
import org.junit.Test

/**
 * The expected grids are the output of kit/screens/src/sprites.py `squid(phase)`, printed
 * with '#' for lit cells. Phase 0 is the Home mockup sprite; 1.2 is the voice mockup's.
 */
class SquidSpriteTest {
    private val phase0 = """
        ..........###..........
        .........#####.........
        ........#######........
        .......####.####.......
        ......###########......
        ......#####.#####......
        .....#############.....
        .....#############.....
        .....###..###..###.....
        .....###..###..###.....
        .....#############.....
        ......###########......
        .....#############.....
        ....#.#.#.#.#.#.#.#....
        ....#.#.#.#.#.#.#.#....
        ....#.#.#.#.#.#.#.#....
        ....#.#.#.#.#.#..#.#...
        ...#.#..#.#.#.#.#..#...
        ..#..#.#.#..#.#.#..#...
        ....#..#.#..#.#.#......
        ....#..#.#..#..#.#.....
        .......#..#.#..#.......
    """.trimIndent()

    private val phase12 = """
        ..........###..........
        .........#####.........
        ........#######........
        .......####.####.......
        ......###########......
        ......#####.#####......
        .....#############.....
        .....#############.....
        .....###..###..###.....
        .....###..###..###.....
        .....#############.....
        ......###########......
        .....#############.....
        ....#.#.#.#.#.#.#.#....
        ....#.#.#.#.#.#.#.#....
        ....#.#.#.#.#.#.#.#....
        ...#..#.#.#.#.#.#.#....
        ...#.#.#..#.#.#.#.#....
        ..#..#.#.#..#.#.#.#....
        .....#.#..#.#..#.#.....
        .....#.#..#..#.#..#....
        ........#.#..#..#......
    """.trimIndent()

    @Test fun phaseZeroMatchesTheKitSpriteExactly() {
        assertThat(SquidSprite.render(SquidSprite.grid(0.0))).isEqualTo(phase0)
    }

    @Test fun midWavePhaseMatchesTheVoiceMockup() {
        assertThat(SquidSprite.render(SquidSprite.grid(1.2))).isEqualTo(phase12)
    }

    @Test fun gridIs23By22() {
        assertThat(SquidSprite.grid().size).isEqualTo(23 * 22)
        assertThat(phase0.lines()).hasSize(SquidSprite.ROWS)
        phase0.lines().forEach { assertThat(it).hasLength(SquidSprite.COLS) }
    }

    @Test fun eyesAreHolesInTheMantle() {
        val g = SquidSprite.grid()
        listOf(8 to 8, 8 to 9, 9 to 8, 9 to 9, 8 to 13, 8 to 14, 9 to 13, 9 to 14).forEach { (r, c) ->
            assertThat(SquidSprite.isEye(r, c)).isTrue()
            assertThat(g[r * SquidSprite.COLS + c]).isFalse()
        }
        assertThat(SquidSprite.isEye(0, 0)).isFalse()
        assertThat(SquidSprite.isEye(8, 11)).isFalse()
    }

    @Test fun posesShareTheHeadAndMoveOnlyTheArms() {
        val standby = SquidPose.STANDBY.grid
        val thinking = SquidPose.THINKING.grid
        val speaking = SquidPose.SPEAKING.grid
        val head = 0 until 14 * SquidSprite.COLS
        head.forEach { i ->
            assertThat(thinking[i]).isEqualTo(standby[i])
            assertThat(speaking[i]).isEqualTo(standby[i])
        }
        assertThat(thinking.contentEquals(standby)).isFalse()
        assertThat(speaking.contentEquals(standby)).isFalse()
        assertThat(SquidPose.STANDBY.armPhase).isEqualTo(0.0)
        assertThat(SquidPose.THINKING.armPhase).isEqualTo(1.2)
    }

    @Test fun armRootsAreTheEightBaseColumns() {
        val g = SquidSprite.grid()
        assertThat(SquidSprite.armBaseColumns).containsExactly(4, 6, 8, 10, 12, 14, 16, 18).inOrder()
        (0 until SquidSprite.COLS).forEach { c ->
            assertThat(g[13 * SquidSprite.COLS + c]).isEqualTo(c in SquidSprite.armBaseColumns)
        }
    }
}
